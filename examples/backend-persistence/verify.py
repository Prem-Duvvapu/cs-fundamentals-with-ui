#!/usr/bin/env python3
"""Owned PostgreSQL histories/incidents, real restore, exact cleanup and source-bound evidence."""
import argparse
import getpass
import hashlib
import json
import os
from pathlib import Path
import re
import secrets
import tempfile
import uuid
import xml.etree.ElementTree as ET

from processes import Budget, LabFailure, cancellation_guard, defer_cancellation, environment as clean_environment, run

ROOT=Path(__file__).resolve().parent
REPOSITORY=ROOT.parent.parent
CASE_FILES=('nplusone','pool','migration','isolation','serialization-retry','retry-exhaustion','deadlock','locking-strategies','composite-index','pagination')
SUITES={'GuardTest':2,'PostgresIncidentTest':3,'PostgresIsolationTest':3,'PostgresLockingTest':2,'PostgresAccessPathTest':2}


def owned_identifier(value):
    if not re.fullmatch(r'lab_(?:persist_(?:role_)?|restore_)[a-f0-9]{32}(?:_source|_restored)?',value):
        raise ValueError('Refusing a resource that was not generated by this lab')
    return '"'+value+'"'


def child_environment(password):
    values=clean_environment()
    values.update(PGPASSWORD=password,PGCONNECT_TIMEOUT='2',
        PGOPTIONS='-c statement_timeout=3000 -c lock_timeout=1000 -c idle_in_transaction_session_timeout=5000')
    return values


class Postgres:
    def __init__(self,host,port,user,password,container=None,budget=None):
        self.host,self.port,self.user,self.password,self.container=host,port,user,password,container
        self.budget=budget if budget is not None else Budget.start(60)
    def run(self,tool,database,*,sql=None,arguments=(),input_bytes=None,timeout=30):
        if tool not in ('psql','pg_dump','pg_restore'):
            raise ValueError('Only reviewed PostgreSQL tools are allowed')
        host,port=('127.0.0.1',5432) if self.container else (self.host,self.port)
        command=[tool,'--host',host,'--port',str(port),'--username',self.user,'--no-password','--dbname',database,*arguments]
        if tool=='psql':
            command+=['-X','-qAt','-v','ON_ERROR_STOP=1']
        if self.container:
            command=['docker','exec','-i','-e','PGPASSWORD','-e','PGCONNECT_TIMEOUT','-e','PGOPTIONS',self.container,*command]
        result=run(command,ROOT,self.budget,input_bytes=sql.encode() if sql is not None else input_bytes,
                   env=child_environment(self.password),timeout=timeout,output_limit=1048576)
        if result.returncode:
            # CREATE ROLE SQL and vendor errors can contain generated secrets; never echo them.
            raise RuntimeError(tool+' failed on an owned resource; no credentials are included here')
        return result.stdout
    def sql(self,database,sql):
        return self.run('psql',database,sql=sql).decode().strip()


def source_hashes():
    files=[ROOT/'pom.xml',*ROOT.glob('*.py'),*(path for path in (ROOT/'src').rglob('*') if path.is_file())]
    if any(path.is_symlink() for path in files):
        raise LabFailure('Reviewed lab source must not be symlinked')
    return {path.relative_to(ROOT).as_posix():hashlib.sha256(path.read_text().encode()).hexdigest() for path in sorted(files)}


def maven(environment,passwords,budget):
    output=ROOT/'target/evidence'; output.mkdir(parents=True,exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='owned-persistence-maven-') as directory:
        settings=Path(directory)/'settings.xml'
        settings.write_text('<settings xmlns="http://maven.apache.org/SETTINGS/1.2.0"/>\n')
        result=run(['mvn','-s',settings,'-gs',settings,'-B','-ntp','-o','-f',ROOT/'pom.xml','verify'],ROOT,budget,
                   env=environment,timeout=180,output_limit=2097152)
    text=(result.stdout+result.stderr).decode(errors='replace')
    for password in passwords:
        if password:
            text=text.replace(password,'[REDACTED]')
    (output/'maven.log').write_text(text)
    if result.returncode:
        raise RuntimeError('Database tests failed; inspect private target/evidence/maven.log locally')
    suites={}
    for name,expected in SUITES.items():
        suite=ET.parse(ROOT/('target/surefire-reports/TEST-com.csfundamentals.persistencelab.'+name+'.xml')).getroot()
        if int(suite.get('tests','0'))!=expected or any(int(suite.get(field,'0')) for field in ('skipped','failures','errors')):
            raise LabFailure('Every required actual database test must run without failures or skips: '+name)
        suites[name]={'tests':expected,'skipped':0,'failures':0,'errors':0}
    return suites


def checked_destination(path):
    path=path.absolute()
    if path.is_symlink() or path.resolve()!=path:
        raise ValueError('Evidence must not traverse symlinks')
    if path.is_relative_to(REPOSITORY) and not path.is_relative_to(ROOT/'target/evidence'):
        raise ValueError('Repository evidence belongs only under this module target/evidence')
    return path


def cleanup(admin,source,restored,role,marker):
    match=re.fullmatch(r'lab_persist_role_([a-f0-9]{32})',role)
    if not match or source!='lab_persist_'+match[1]+'_source' or restored!='lab_persist_'+match[1]+'_restored' or marker!='backend-persistence:'+match[1]:
        raise ValueError('Cleanup requires one exact generated resource family')
    admin.budget=Budget.start(90)
    # Exact catalog identity and immutable run marker: an inspect error is never absence evidence.
    observed=admin.sql('postgres',"SELECT coalesce(shobj_description(oid,'pg_authid'),'') FROM pg_roles WHERE rolname='"+role+"'")
    owners={name:admin.sql('postgres',"SELECT pg_get_userbyid(datdba) FROM pg_database WHERE datname='"+name+"'") for name in (source,restored)}
    if observed and observed!=marker:
        raise LabFailure('Refusing changed role ownership marker')
    if any(owner and (owner!=role or observed!=marker) for owner in owners.values()):
        raise LabFailure('Refusing database with changed ownership')
    for name in (restored,source):
        if owners[name]:
            admin.sql('postgres','DROP DATABASE '+owned_identifier(name)+' WITH (FORCE)')
        if admin.sql('postgres',"SELECT count(*) FROM pg_database WHERE datname='"+name+"'")!='0':
            raise LabFailure('Owned database remains after cleanup')
    if observed:
        admin.sql('postgres','DROP ROLE '+owned_identifier(role))
    if admin.sql('postgres',"SELECT count(*) FROM pg_roles WHERE rolname='"+role+"'")!='0':
        raise LabFailure('Owned role remains after cleanup')


def verify(report_path):
    report_path=checked_destination(report_path)
    report_path.unlink(missing_ok=True)
    mode=os.environ.get('PERSISTENCE_ADMIN_MODE')
    if mode not in ('socket','tcp'):
        raise ValueError('Explicitly select PERSISTENCE_ADMIN_MODE=socket or tcp for an owned local PostgreSQL server')
    port=int(os.environ.get('PERSISTENCE_ADMIN_PORT','5432'))
    if not 1<=port<=65535:
        raise ValueError('Invalid local server port')
    container=os.environ.get('PERSISTENCE_PG_TOOL_CONTAINER')
    if container and (mode!='tcp' or not re.fullmatch(r'persistence-pg-[A-Za-z0-9-]{1,64}',container)):
        raise ValueError('Container tooling requires the explicitly owned CI container name')
    budget=Budget.start()
    if container:
        if os.environ.get('DOCKER_HOST') or os.environ.get('DOCKER_CONTEXT'):
            raise ValueError('Docker endpoint overrides refused')
        endpoint=run(['docker','context','inspect','--format','{{.Endpoints.docker.Host}}'],ROOT,budget,timeout=10)
        if endpoint.returncode or not endpoint.stdout.decode().strip().startswith('unix://'):
            raise ValueError('Explicit local Unix Docker daemon required')
    if mode=='tcp':
        if os.environ.get('PERSISTENCE_ADMIN_HOST')!='127.0.0.1':
            raise ValueError('TCP administrator must explicitly use loopback IPv4')
        admin_password=os.environ.get('PERSISTENCE_ADMIN_PASSWORD','')
        if len(admin_password)<32:
            raise ValueError('TCP administrator requires a generated runtime password')
        admin=Postgres('127.0.0.1',port,os.environ.get('PERSISTENCE_ADMIN_USER','postgres'),admin_password,container,budget)
    else:
        if container:
            raise ValueError('Socket mode uses the existing local tools')
        admin_password=''
        admin=Postgres('/var/run/postgresql',port,getpass.getuser(),'',None,budget)
    identifier=uuid.uuid4().hex
    source,restored,role='lab_persist_'+identifier+'_source','lab_persist_'+identifier+'_restored','lab_persist_role_'+identifier
    marker='backend-persistence:'+identifier
    password=secrets.token_hex(32)
    source_before=source_hashes()
    report={'schemaVersion':2,'scenario':'actual-postgresql-concurrency-and-incidents'}
    for name in CASE_FILES:
        (ROOT/('target/evidence/'+name+'.json')).unlink(missing_ok=True)
    try:
        # The role and run marker commit together; exact metadata permits cleanup after an unknown client result.
        with defer_cancellation():
            admin.sql('postgres',f"BEGIN; CREATE ROLE {owned_identifier(role)} LOGIN CONNECTION LIMIT 4 PASSWORD '{password}'; COMMENT ON ROLE {owned_identifier(role)} IS '{marker}'; COMMIT;")
        for database in (source,restored):
            admin.sql('postgres',f'CREATE DATABASE {owned_identifier(database)} OWNER {owned_identifier(role)}')
        actual=Postgres('127.0.0.1',port,role,password,container,budget)
        environment=clean_environment()
        environment.update(PERSISTENCE_TESTS='true',PERSISTENCE_JDBC_URL=f'jdbc:postgresql://127.0.0.1:{port}/{source}',
                           PERSISTENCE_DB_USER=role,PERSISTENCE_DB_PASSWORD=password)
        report['testSuites']=maven(environment,(password,admin_password),budget)
        for name in CASE_FILES:
            report[name]=json.loads((ROOT/('target/evidence/'+name+'.json')).read_text())
        schema = 'lab_restore_' + uuid.uuid4().hex
        quote = owned_identifier(schema)
        actual.sql(source, f'''
CREATE SCHEMA {quote};
CREATE TABLE {quote}.accounts(id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,label TEXT UNIQUE NOT NULL,balance INT NOT NULL CHECK(balance>=0));
CREATE TABLE {quote}.entries(id INT PRIMARY KEY,account_id BIGINT NOT NULL REFERENCES {quote}.accounts(id),amount INT NOT NULL);
INSERT INTO {quote}.accounts(label,balance) VALUES('alpha',10),('beta',20),('gamma',30);
INSERT INTO {quote}.entries VALUES(1,1,10),(2,2,20),(3,3,30);
''')
        dataset = f"SELECT json_build_object('accounts',(SELECT json_agg(a ORDER BY id) FROM {quote}.accounts a),'entries',(SELECT json_agg(e ORDER BY id) FROM {quote}.entries e))"
        before = actual.sql(source, dataset)
        with tempfile.TemporaryDirectory(prefix='owned-persistence-dump-') as directory:
            dump = actual.run('pg_dump', source, arguments=('--format=custom', '--no-owner', '--no-privileges', '--lock-wait-timeout=3s', '--schema=' + schema))
            if len(dump) > 1_048_576:
                raise RuntimeError('Tiny fixture dump unexpectedly exceeds one MiB')
            archive = Path(directory) / 'fixture.dump'
            archive.write_bytes(dump)
            actual.run('pg_restore', restored, arguments=('--exit-on-error', '--single-transaction', '--no-owner', '--no-privileges'), input_bytes=archive.read_bytes())
        after = actual.sql(restored, dataset)
        assert before == after, 'Restored original fixtures differ'
        actual.sql(restored, f'''
DO $$ BEGIN
    BEGIN INSERT INTO {quote}.entries VALUES(99,999,1); RAISE EXCEPTION 'Missing foreign key';
    EXCEPTION WHEN foreign_key_violation THEN NULL; END;
    BEGIN INSERT INTO {quote}.accounts(label,balance) VALUES('invalid',-1); RAISE EXCEPTION 'Missing balance check';
    EXCEPTION WHEN check_violation THEN NULL; END;
END $$;
''')
        next_identity = int(actual.sql(restored, f"SELECT nextval(pg_get_serial_sequence('{schema}.accounts','id'))"))
        # The rejected CHECK insert consumes identity value 4; PostgreSQL sequences do not roll back.
        assert next_identity == 5, 'Identity sequence state was not preserved through dump/restore'
        report['restore'] = {'source_accounts': 3, 'restored_accounts': 3, 'restored_entries': 3,
                             'dataset_sha256': hashlib.sha256(before.encode()).hexdigest(),
                             'equivalent_dataset': True, 'foreign_key_enforced': True,
                             'check_constraint_enforced': True, 'next_identity_after_rejected_insert': next_identity}
        report['postgres_version_num'] = int(actual.sql(source, 'SHOW server_version_num'))
        report['evidence_scope']='Actual local PostgreSQL histories, locking, plans, JPA, Hikari and pg_dump/pg_restore; not production capacity, distributed consistency or HA evidence'
    finally:
        with defer_cancellation():
            cleanup(admin,source,restored,role,marker)
    if source_hashes()!=source_before:
        raise LabFailure('Reviewed persistence source changed during execution')
    report['owned_resources_cleaned']=True
    report['actualCaseGroups']=10
    report['sourceSha256LF']=source_before
    report_path.parent.mkdir(parents=True,exist_ok=True)
    encoded=json.dumps(report,indent=2)+'\n'
    if len(encoded.encode())>65536:
        raise LabFailure('Sanitized aggregate evidence cap')
    temporary=report_path.with_suffix('.tmp')
    temporary.write_text(encoded); temporary.replace(report_path)
    print('PASS: ten actual PostgreSQL case groups, original backup/restore and exact owned cleanup.')
    print('Evidence: '+str(report_path))


if __name__=='__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--report',type=Path,default=ROOT/'target/evidence/verification.json')
    with cancellation_guard():
        verify(parser.parse_args().report)
